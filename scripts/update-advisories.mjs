// Maintainer tool: regenerates src/data/openclaw-advisories.ts from npm's
// bulk advisory endpoint (the GitHub-reviewed data `npm audit` uses). This is
// the only network access in the repository; the scanner never runs it.
//
//   node scripts/update-advisories.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const packages = ["openclaw", "clawdbot", "moltbot"];
const endpoint = "https://registry.npmjs.org/-/npm/v1/security/advisories/bulk";

const request = {};
for (const name of packages) {
  const raw = execFileSync("npm", ["view", name, "versions", "--json"], { encoding: "utf8" });
  const versions = JSON.parse(raw);
  request[name] = Array.isArray(versions) ? versions : [versions];
}

const response = await fetch(endpoint, {
  method: "POST",
  headers: { "content-type": "application/json" },
  body: JSON.stringify(request),
});
if (!response.ok) {
  throw new Error(`Advisory request failed: HTTP ${response.status}`);
}
const body = await response.json();

const seen = new Set();
const advisories = [];
for (const name of packages) {
  for (const advisory of body[name] ?? []) {
    const ghsa = /GHSA-[0-9a-z]{4}-[0-9a-z]{4}-[0-9a-z]{4}/.exec(advisory.url)?.[0];
    if (!ghsa) {
      throw new Error(`Advisory without a GHSA id: ${advisory.url}`);
    }
    const key = `${name}:${ghsa}`;
    if (seen.has(key)) continue;
    seen.add(key);
    advisories.push({
      ghsa,
      package: name,
      severity: advisory.severity,
      vulnerableVersions: advisory.vulnerable_versions,
      title: advisory.title,
    });
  }
}
advisories.sort((a, b) => a.ghsa.localeCompare(b.ghsa) || a.package.localeCompare(b.package));

const fetchedAt = new Date().toISOString().slice(0, 10);
const source = `${endpoint} (${packages.join(", ")})`;
const file = `// Generated by scripts/update-advisories.mjs. Do not edit by hand.
import type { BundledAdvisory } from "../checks/version-advisories.js";

export const advisoryDataDate = ${JSON.stringify(fetchedAt)};
export const advisoryDataSource = ${JSON.stringify(source)};

export const bundledAdvisories: readonly BundledAdvisory[] = ${JSON.stringify(advisories, null, 2)};
`;
writeFileSync(new URL("../src/data/openclaw-advisories.ts", import.meta.url), file);
console.log(`Wrote ${advisories.length} advisories dated ${fetchedAt}.`);
